/**
 * optmat_calc_refractive_index_pmma - Calculate refractive index of PMMA resist
 * @lambdanm: Wavelength in nanometers
 *
 * Tabulated refractive index data (400 nm to 1000 nm) with linear interpolation.
 *
 * Return: Refractive index n.
 */
double optmat_calc_refractive_index_pmma(double lambdanm)
{
    if (lambdanm > 1000.0)
    {
        fprintf(stderr, "ERROR: PMMA refractive index data does not exist past 1000nm\n");
        exit(EXIT_FAILURE);
    }

    if (lambdanm < 400.0)
    {
        return pmma_table[0];
    }
    if (lambdanm >= 1000.0)
    {
        return pmma_table[600];
    }

    long i1 = (long) lambdanm;
    long i2 = i1 + 1;
    double ifrac = lambdanm - (double) i1;
    double n1 = pmma_table[i1 - 400];
    double n2 = pmma_table[i2 - 400];

    return n1 * (1.0 - ifrac) + n2 * ifrac;
}
