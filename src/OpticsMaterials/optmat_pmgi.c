/**
 * optmat_calc_refractive_index_pmgi - Calculate refractive index of PMGI resist
 * @lambdanm: Wavelength in nanometers
 *
 * Tabulated refractive index data (400 nm to 1000 nm) with linear interpolation.
 *
 * Return: Refractive index n.
 */
double optmat_calc_refractive_index_pmgi(double lambdanm)
{
    if (lambdanm > 1000.0)
    {
        fprintf(stderr, "ERROR: PMGI refractive index data does not exist past 1000nm\n");
        exit(EXIT_FAILURE);
    }

    if (lambdanm < 400.0)
    {
        return pmgi_table[0];
    }
    if (lambdanm >= 900.0)
    {
        return pmgi_table[500];
    }

    long i1 = (long) lambdanm;
    long i2 = i1 + 1;
    double ifrac = lambdanm - (double) i1;
    double n1 = pmgi_table[i1 - 400];
    double n2 = pmgi_table[i2 - 400];

    return n1 * (1.0 - ifrac) + n2 * ifrac;
}
